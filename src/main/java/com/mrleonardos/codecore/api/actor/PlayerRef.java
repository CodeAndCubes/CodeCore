package com.mrleonardos.codecore.api.actor;

import java.util.UUID;

/**
 * Ссылка на игрока: идентификатор и ник, больше ничего.
 *
 * <p>
 * Всё, что делают с настоящим игроком (телепорт, выдача предмета, отправка сообщения), живёт в слоях
 * платформы, а через границу api ходит только ссылка. Так api переживает переезд на другую версию игры:
 * тип сущности игрока между версиями меняется, пара «идентификатор и ник» нет.
 *
 * <p>
 * Ссылка не обещает, что игрок сейчас на сервере. Вернуться от неё к сущности умеет слой платформы ядра,
 * класс {@code com.mrleonardos.codecore.platform.PlayerRefs}.
 */
public interface PlayerRef {

    /** Идентификатор игрока: он же ключ во всех хранилищах линейки. */
    UUID id();

    /** Ник, каким игрок значился в момент, когда ссылку сделали. */
    String name();

    /**
     * Готовая ссылка по паре значений.
     *
     * <p>
     * Две ссылки равны, когда равны идентификаторы: ник переименовывается, идентификатор нет. Поэтому
     * ссылку можно класть в множество получателей и не бояться, что один игрок попадёт туда дважды под
     * старым и новым ником.
     */
    static PlayerRef of(UUID id, String name) {
        return new PlayerRefValue(id, name);
    }
}
