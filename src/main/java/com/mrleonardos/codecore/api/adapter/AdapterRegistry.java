package com.mrleonardos.codecore.api.adapter;

import java.util.List;
import java.util.Set;

/**
 * Кто держит каждую область ответственности: наш мод, мост к чужому моду или никто.
 *
 * <p>
 * Выбор делается по роли целиком одним ключом в секции {@code [owners]} главного файла. Значение
 * принимает три вида: {@code auto} (наш мод, если он стоит), {@code off} (роль не занята никем) и имя
 * владельца. Незнакомое имя уходит по правилу {@code auto} с записью в лог: молча оставить сервер без
 * прав из-за опечатки хуже, чем взять заводское поведение и сказать об этом.
 *
 * <p>
 * Порядок такой. В фазе init роль объявляют через {@link #declareRole(RoleSpec)}, а заявки подают через
 * {@link #offer(RoleAdapter)}. В конце постинициализации ядро решает каждую роль, зовёт
 * {@link RoleAdapter#create()} у победителя и регистрирует его реализации в реестре сервисов. После
 * этого и объявление, и заявка отклоняются исключением.
 *
 * <p>
 * Мод, чью роль держит кто-то другой, отходит целиком: не регистрирует команд, не открывает файлов и не
 * подписывается на события мира. Владельца он спрашивает на старте сервера, когда решение уже принято.
 */
public interface AdapterRegistry {

    /**
     * Объявить роль и полный перечень её умений.
     *
     * @throws IllegalStateException    если роли уже решены
     * @throws IllegalArgumentException если эту роль уже объявили
     */
    void declareRole(RoleSpec spec);

    /**
     * Подать заявку на роль.
     *
     * @throws IllegalStateException если роли уже решены
     */
    void offer(RoleAdapter adapter);

    /**
     * Имя владельца роли или {@code null}, если роль не занята никем.
     *
     * @throws IllegalStateException пока роли не решены: тогда {@code null} значил бы и «роль ничья», и
     *                               «ещё не считали», а отличить одно от другого спрашивающему нечем
     */
    String owner(String role);

    /** Имена всех заявок роли; заявка, чьего мода на сервере нет, помечена звёздочкой. */
    List<String> candidates(String role);

    /**
     * Умения роли, которых у её владельца нет.
     *
     * @throws IllegalStateException пока роли не решены: пустой перечень читался бы как «владелец умеет
     *                               всё», полный как «не работает ничего», и оба ответа неотличимы от
     *                               правды. Спросить о фазе заранее можно через {@link #decided()}
     */
    Set<RoleCapability> missing(String role);

    /** Все объявленные роли в порядке объявления. */
    List<String> roles();

    /** Чем кончился выбор по каждой роли. */
    List<RoleStatus> statuses();

    /** Решены ли роли: до конца постинициализации нет. */
    boolean decided();
}
