package com.mrleonardos.codecore.api.client.image;

/** Как вписать картинку произвольных пропорций в квадрат. */
public enum ImageFit {

    /** Заполнить квадрат целиком, лишнее по длинной стороне обрезать. Подходит аватарам. */
    COVER,

    /** Уместить целиком, недостающее оставить прозрачным. Подходит гербам и значкам. */
    CONTAIN
}
