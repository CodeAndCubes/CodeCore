package com.mrleonardos.codecore.api.client.image;

/**
 * Загрузка и подготовка картинок для интерфейса.
 *
 * <p>
 * Что делает сервис: качает или читает файл, приводит к нужному размеру, кладёт результат в кэш на диске
 * и отдаёт текстуру. Повторная просьба о том же источнике и размере не порождает вторую загрузку, а
 * неудачный адрес какое-то время не трогается вовсе.
 *
 * <p>
 * Форматы: png, jpeg и gif (первый кадр) читаются всегда; webp только при наличии декодера в сборке.
 */
public interface ImageService {

    /** Попросить картинку. Возвращается сразу, загрузка идёт в стороне. */
    ImageHandle request(ImageRequest request);

    /** Забыть загруженное: текстуры выгружаются, кэш на диске остаётся. */
    void clearMemory();

    /** Поддерживается ли формат по расширению или mime-типу. */
    boolean supports(String formatHint);
}
