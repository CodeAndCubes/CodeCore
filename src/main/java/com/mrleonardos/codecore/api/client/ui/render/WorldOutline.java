package com.mrleonardos.codecore.api.client.ui.render;

import java.util.List;

/**
 * Рамки и сетки в мире.
 *
 * <p>
 * Берётся из {@code ClientApi.outline()}. Подписка на отрисовку мира одна на всю линейку: заведи её
 * каждый мод у себя, и чинить мерцание, прозрачность и порядок рисования пришлось бы в каждом.
 *
 * <p>
 * Набор боксов живёт под ключом. Повторный {@link #show} с тем же ключом заменяет набор целиком, поэтому
 * двигающееся выделение не требует снимать и заводить рамку заново. Ключ свой у каждого мода: имя мода
 * впереди спасает от того, что два мода назовут набор {@code selection}.
 *
 * <p>
 * Рамка гаснет сама при смене мира и при выходе с сервера. Набор, оставшийся от прошлого сервера, к
 * следующему отношения не имеет.
 */
public interface WorldOutline {

    /**
     * Показать набор боксов под ключом, заменив прежний набор этого ключа.
     *
     * <p>
     * Пустой список равносилен {@link #hide(String)}: проверять список на пустоту перед вызовом не надо.
     */
    void show(String key, OutlineStyle style, List<OutlineBox> boxes);

    /** Убрать набор. Неизвестный ключ не ошибка. */
    void hide(String key);

    /** Есть ли сейчас набор под этим ключом. */
    boolean shown(String key);

    /** Убрать все наборы: зовётся ядром при смене мира, модам обычно нужен {@link #hide(String)}. */
    void clear();
}
