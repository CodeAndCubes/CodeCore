package com.mrleonardos.codecore.api.command;

/**
 * Кто выполняет команду.
 *
 * <p>
 * Различать эти четыре вида приходится всем: права даются всем, кроме игрока, без проверки файла, а в
 * журнале правки подписывается тот, кто её сделал. Раньше это решалось цепочкой {@code instanceof} по
 * классам игры, из-за чего мод, которому нужен был только вид отправителя, тащил за собой
 * {@code CommandBlockLogic} и {@code RConConsoleSource}.
 */
public enum SenderKind {

    /** Игрок на сервере. */
    PLAYER,

    /** Консоль сервера. */
    CONSOLE,

    /** Удалённая консоль по RCON. */
    RCON,

    /** Командный блок в мире. */
    COMMAND_BLOCK
}
