package com.mrleonardos.codecore.api.config;

import java.nio.file.Path;

/**
 * Открытый файл настроек: доступ к разобранным значениям, сохранение и перечитывание.
 *
 * <p>
 * Объект живёт всё время работы мода, а вот содержимое может перезагружаться командой
 * {@code reload} или сменой мира для {@link ConfigScope#WORLD_STATE}. Поэтому значение берётся вызовом
 * {@link #get()} каждый раз, а не запоминается в поле при старте.
 */
public interface ConfigFile<T> {

    /**
     * Текущие значения.
     *
     * @throws IllegalStateException если файл ещё не загружен; так бывает у настроек мира, пока мир не
     *                               открыт
     */
    T get();

    /** Загружены ли значения прямо сейчас. */
    boolean loaded();

    /** Записать текущие значения на диск. */
    void save();

    /** Перечитать файл с диска, потеряв несохранённые изменения. */
    void reload();

    /** Путь к файлу или {@code null}, если он ещё неизвестен. */
    Path path();
}
