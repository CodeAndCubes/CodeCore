package com.mrleonardos.codecore.api.config;

/**
 * Назначение файла настроек: что с ним происходит при переносе сервера или сохранения.
 *
 * <p>
 * Разделение принципиальное: настройки админ переносит между серверами и держит в системе контроля
 * версий, а состояние принадлежит конкретному миру и обязано переезжать вместе с ним. Свалить их в одну
 * папку значит однажды потерять половину данных при переносе сохранения.
 *
 * <p>
 * Путь целиком собирает ядро из роли, скоупа, владельца и имени.
 */
public enum ConfigScope {

    /** Настройки сервера: {@code config/code/<роль>/<файл>}. */
    SETTINGS,

    /** Предпочтения игрока: {@code config/code/<роль>/client/<файл>}. */
    CLIENT,

    /** Состояние мира: {@code <мир>/code/<роль>/<файл>}. Доступно только когда мир загружен. */
    WORLD_STATE
}
