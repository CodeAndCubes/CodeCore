package com.mrleonardos.codecore.api.config;

import java.nio.file.Path;

/**
 * Файлы настроек линейки: toml для того, что правят руками, json для того, что пишет только мод.
 *
 * <p>
 * Всё лежит в одной папке {@code config/code}, разложенное по областям ответственности. Открывать файлы
 * нужно один раз при инициализации мода и держать полученный {@link ConfigFile}: повторное открытие того
 * же файла вернёт тот же объект.
 *
 * <p>
 * Общие для линейки настройки живут в одном файле {@code config/code/config.toml}, и каждый мод приносит
 * туда свою секцию через {@link #section(SectionSpec)}.
 */
public interface ConfigService {

    /**
     * Открыть файл. Настройки сервера и клиента читаются сразу, состояние мира после загрузки мира.
     * Отсутствующий файл создаётся со значениями по умолчанию.
     */
    <T> ConfigFile<T> open(ConfigSpec<T> spec);

    /**
     * Объявить свою секцию главного файла и получить доступ к её значениям.
     *
     * <p>
     * Зовётся в фазе init: набор секций должен быть готов к тому моменту, когда ядро в конце
     * постинициализации пишет файл целиком.
     *
     * @throws IllegalStateException если секции уже собраны или эту секцию объявил кто-то ещё
     */
    <T> ConfigFile<T> section(SectionSpec<T> spec);

    /** Содержимое главного файла как есть: для того, чего не описали секцией. */
    ConfigData main();

    /**
     * Имя этого сервера из главного файла.
     *
     * <p>
     * Нужно, когда несколько серверов смотрят в одну базу: схемы модов сами решают, что размечать этим
     * именем, а что держать общим.
     */
    String serverId();

    /** Настройки хранилища для роли с учётом секции {@code [storage.<роль>]}, если она есть. */
    StorageSettings storage(String role);

    /** Настройки журнала для роли с учётом секции {@code [audit.<роль>]}, если она есть. */
    AuditSettings audit(String role);

    /**
     * Папка области ответственности: {@code config/code/<роль>}.
     *
     * <p>
     * Для того, что не настройки: кэша картинок, выгрузок, вложенных наборов данных. Папка может ещё не
     * существовать; создаёт её тот, кто пишет.
     */
    Path directory(String role);

    /** Перечитать с диска всё, что открыто: за этим стоит команда перезагрузки конфигов. */
    void reloadAll();
}
