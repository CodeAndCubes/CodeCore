package com.mrleonardos.codecore.api.config;

import java.nio.file.Path;

/**
 * Работа с файлами настроек: json, схема с версией, миграции и атомарная запись.
 *
 * <p>
 * Открывать файлы нужно один раз при инициализации мода и держать полученный {@link ConfigFile}:
 * повторное открытие того же файла вернёт тот же объект.
 */
public interface ConfigService {

    /**
     * Открыть файл. Настройки сервера и клиента читаются сразу, состояние мира после загрузки мира.
     * Отсутствующий файл создаётся со значениями по умолчанию.
     */
    <T> ConfigFile<T> open(ConfigSpec<T> spec);

    /**
     * Папка настроек мода.
     *
     * <p>
     * Для того, что не json: картинок, кэша, вложенных наборов данных. Папка может ещё не
     * существовать; создаёт её тот, кто пишет.
     */
    Path directory(String modid);

    /** Перечитать с диска всё, что открыто: за этим стоит команда перезагрузки конфигов. */
    void reloadAll();
}
