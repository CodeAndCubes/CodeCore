package com.mrleonardos.codecore.api.config;

import com.google.gson.JsonObject;

/**
 * Шаг превращения файла настроек из одной версии схемы в следующую.
 *
 * <p>
 * Работает с сырым json до разбора в объект: на момент миграции старые поля ещё существуют, а новых
 * классов уже нет. Шаги выстраиваются в цепочку по номерам версий и применяются по порядку.
 */
public interface Migration {

    /** Версия схемы, из которой шаг умеет переводить. */
    int from();

    /** Версия схемы, в которую шаг переводит. Обычно {@code from() + 1}. */
    int to();

    /** Изменить данные на месте: переименовать поля, разложить их иначе, проставить новые значения. */
    void apply(JsonObject data);
}
