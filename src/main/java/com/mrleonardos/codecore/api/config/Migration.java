package com.mrleonardos.codecore.api.config;

/**
 * Шаг превращения файла настроек из одной версии схемы в следующую.
 *
 * <p>
 * Работает с содержимым файла до разбора в объект: на момент миграции старые ключи ещё существуют, а
 * новых классов уже нет. Шаги выстраиваются в цепочку по номерам версий и применяются по порядку.
 *
 * <p>
 * Дерево одно и то же для toml и json, поэтому шаг переживает смену формата файла.
 */
public interface Migration {

    /** Версия схемы, из которой шаг умеет переводить. */
    int from();

    /** Версия схемы, в которую шаг переводит. Обычно {@code from() + 1}. */
    int to();

    /** Изменить данные на месте: переименовать ключи, разложить их иначе, проставить новые значения. */
    void apply(ConfigData data);
}
