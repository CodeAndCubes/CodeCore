package com.mrleonardos.codecore.api.db;

import java.util.List;

/**
 * Базы данных линейки: описаны в одном файле настроек, выдаются по имени.
 *
 * <p>
 * Сервис лежит в реестре ядра весом {@code BUILTIN}, поэтому чужой мод вправе принести свою реализацию
 * с любым движком. Встроенная знает два: MariaDB и SQLite.
 *
 * <p>
 * Основной путь для мода это {@link #database(String)} с идентификатором из настроек. Поиск по роли
 * нужен там, где установка типовая и запись с такой меткой одна; неоднозначность решает администратор
 * ключом в настройках, а не мод угадыванием.
 */
public interface DatabaseService {

    /**
     * База по идентификатору из настроек.
     *
     * @throws UnknownDatabaseException если записи с таким идентификатором нет
     */
    Database database(String id);

    /**
     * База по метке роли.
     *
     * @throws UnknownDatabaseException если записи с меткой нет, а также если их несколько и
     *                                  администратор не выбрал одну в {@code roleDefaults}
     */
    Database byRole(String role);

    /** Короткое имя для базы с ролью {@code global}. */
    Database global();

    /** Короткое имя для базы с ролью {@code server}. */
    Database server();

    /** Идентификаторы записей из настроек в порядке файла. */
    List<String> ids();

    /** Метки ролей, которые встречаются в настройках. */
    List<String> roles();

    /**
     * Имя этого сервера в установке из нескольких серверов.
     *
     * <p>
     * Берётся из главного файла линейки. Ядро значение не разбирает: где строки общие, а где помечены
     * сервером, решает схема мода.
     */
    String serverId();
}
