package com.mrleonardos.codecore.api.service;

import com.mrleonardos.codecore.api.actor.PlayerRef;

/**
 * Строка над хотбаром.
 *
 * <p>
 * Место для коротких причин: отказ привата, потолок механизмов, снятый полёт. В чат такое слать нельзя,
 * потому что причин бывает десяток в секунду, и через минуту у игрока в чате не останется ничего, кроме
 * них.
 *
 * <p>
 * Пакета для этой строки в 1.7.10 нет: {@code S02PacketChat} несёт компонент и флаг «это чат», а поле
 * типа сообщения появилось только в 1.8. Поэтому строку рисует клиент по пакету ядра, и мод линейки, у
 * которого клиент обязателен, получает её даром. Клиент без ядра не увидит ничего, и это не ошибка:
 * такой строки у него попросту негде показать.
 *
 * <p>
 * Антиспам здесь не украшение, а половина смысла. Строка с одним ключом показывается не чаще, чем раз в
 * окно {@link ActionBarLine#repeatSeconds()}, а меньше наименьшего окна из главного файла ядра его не
 * сделать. Без этого сервис превращается в тот же чат, только поверх экрана.
 *
 * <p>
 * Очереди нет. Свежая строка сменяет показанную: причина, которая только что случилась, важнее той, что
 * случилась секунду назад.
 */
public interface ActionBarService {

    /**
     * Показать строку игроку.
     *
     * <p>
     * Показ, зажатый антиспамом, отбрасывается молча: зовущий обычно не в том положении, чтобы решать,
     * что делать с непоказанной строкой, а вернуть ему ответ значит попросить его этот ответ проверять.
     */
    void show(PlayerRef player, ActionBarLine line);
}
