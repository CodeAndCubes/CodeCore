package com.mrleonardos.codecore.api.service;

import java.util.Optional;

/**
 * Реестр сервисов ядра: интерфейс объявляется один раз, а реализацию подставляет тот мод, который умеет
 * это лучше.
 *
 * <p>
 * Смысл в подменяемости. CodeChat спрашивает {@code PermissionService} и не знает, отвечает ли ему
 * встроенная реализация на json-группах или полноценный CodePerms.
 *
 * <p>
 * Регистрировать в фазе инициализации мода, запрашивать не раньше постинициализации: после неё
 * реестр замораживается, и набор реализаций перестаёт зависеть от порядка загрузки модов.
 */
public interface ServiceRegistry {

    /**
     * Предложить реализацию сервиса. Предложение с большим весом вытесняет предыдущее; меньший или
     * равный вес игнорируется с предупреждением в лог.
     *
     * @throws IllegalStateException если реестр уже заморожен
     */
    <T> void register(Class<T> type, T implementation, ServicePriority priority);

    /**
     * Получить реализацию сервиса.
     *
     * @throws ServiceNotFoundException если сервис никто не предоставил
     */
    <T> T require(Class<T> type);

    /** Получить реализацию, если она есть; для необязательных зависимостей. */
    <T> Optional<T> find(Class<T> type);

    /** Заморожен ли реестр: после заморозки регистрация запрещена. */
    boolean frozen();
}
