package com.mrleonardos.codecore.api.util;

/**
 * Выполнение задач в главном потоке своей стороны.
 *
 * <p>
 * Всё, что трогает мир, игроков или инвентари, обязано идти отсюда: обработчики сетевых пакетов и любые
 * фоновые потоки работают вне главного потока, и прямое обращение к миру оттуда даёт гонки и случайные
 * падения без внятного стектрейса.
 *
 * <p>
 * {@link #onMainThread(Runnable)} выбирает сторону сам: на выделенном сервере это всегда серверный тик, на
 * клиенте — серверный для серверного потока и клиентский для остальных. В одиночной игре обе стороны живут
 * в одном процессе, и фоновый поток мода угадать невозможно, поэтому серверный код зовёт
 * {@link #onServerThread(Runnable)}, а рисующий {@link #onClientThread(Runnable)}.
 */
public interface Scheduler {

    /** Выполнить в ближайшем тике главного потока своей стороны. */
    void onMainThread(Runnable task);

    /** Выполнить через указанное число тиков. Ноль равнозначен {@link #onMainThread(Runnable)}. */
    void afterTicks(int ticks, Runnable task);

    /** Выполнить в ближайшем серверном тике, откуда бы ни пришёл вызов. */
    default void onServerThread(Runnable task) {
        onMainThread(task);
    }

    /** Выполнить в ближайшем клиентском тике, откуда бы ни пришёл вызов. */
    default void onClientThread(Runnable task) {
        onMainThread(task);
    }
}
