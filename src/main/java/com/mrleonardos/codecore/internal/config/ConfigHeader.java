package com.mrleonardos.codecore.internal.config;

import java.util.ArrayList;
import java.util.Arrays;
import java.util.List;

/**
 * Шапка файла настроек: то, что стоит над первой строкой.
 *
 * <p>
 * Правило про комментарии живёт здесь одним текстом на всю линейку, а не строкой в каждом моде. Иначе это
 * то же перечисление по файлам, которое разъезжается молча: пять копий одной фразы расходятся так же, как
 * расходились перечни умений роли.
 *
 * <p>
 * Правило приходится говорить вслух, потому что оно неочевидно и обнаруживается потерей: описание над
 * полем принадлежит моду и переписывается при каждой записи, а строка над своим ключом остаётся. До
 * дозаписи это почти не всплывало, потому что файл, который никто не менял, и не переписывался.
 */
final class ConfigHeader {

    private static final String[] NOTICE = {
        "Описание над полем пишет мод, оно перезаписывается при каждой записи файла.",
        "Свою заметку кладите над своим ключом: такую строку мод не трогает." };

    private ConfigHeader() {}

    /** Шапка файла: сначала то, что сказал о себе мод, потом общее правило линейки. */
    static String[] with(String... own) {
        List<String> lines = new ArrayList<>(Arrays.asList(own));
        lines.addAll(Arrays.asList(NOTICE));
        return lines.toArray(new String[0]);
    }
}
