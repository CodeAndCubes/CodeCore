package com.mrleonardos.codecore.internal.config;

/** Чем закончился проход по цепочке миграций. */
public enum MigrationOutcome {

    /** Версия уже целевая: миграциям делать нечего, а дописать новые настройки можно. */
    UNCHANGED,

    /**
     * Файл из будущей версии мода: его не трогают вовсе.
     *
     * <p>
     * Отдельно от {@link #UNCHANGED} намеренно. Оба означают «миграции не работали», но разное дальше:
     * файл текущей версии дополняется новыми настройками, а файл, который писал мод новее нашего, мы
     * читаем как умеем и не переписываем. Одно имя на два смысла уже стоило нам того, что новые
     * настройки не доезжали до существующих файлов.
     */
    AHEAD,

    /** Цепочка дошла до целевой версии, данные изменились. */
    MIGRATED,

    /** Цепочка оборвалась на полпути: часть данных осталась в старом виде. */
    INCOMPLETE
}
