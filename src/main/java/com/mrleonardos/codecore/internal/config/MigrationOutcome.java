package com.mrleonardos.codecore.internal.config;

/** Чем закончился проход по цепочке миграций. */
public enum MigrationOutcome {

    /** Версия уже целевая или файл из будущей версии мода: трогать его нечем. */
    UNCHANGED,

    /** Цепочка дошла до целевой версии, данные изменились. */
    MIGRATED,

    /** Цепочка оборвалась на полпути: часть данных осталась в старом виде. */
    INCOMPLETE
}
